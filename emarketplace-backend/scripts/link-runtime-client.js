'use strict';
/**
 * Post-build step: swap the compiled type-stub runtime for the pg-backed
 * PrismaClient adapter (prisma/client.js).
 *
 * dist/generated/prisma/index.js is emitted from a type-only stub, so its
 * runtime exports are empty. This script overwrites it with a CommonJS shim
 * that re-exports everything from prisma/client.js — the real, working client.
 */
const fs = require('fs');
const path = require('path');

const distIndex = path.join(__dirname, '..', 'dist', 'generated', 'prisma', 'index.js');
if (!fs.existsSync(distIndex)) {
  console.error(`[link-runtime-client] expected build output not found: ${distIndex}`);
  process.exit(1);
}

const shim = [
  `'use strict';`,
  `// AUTO-GENERATED by scripts/link-runtime-client.js — do not edit.`,
  `// Runtime bindings come from the pg-backed PrismaClient adapter.`,
  `const path = require('path');`,
  `const root = process.env.APP_ROOT || path.resolve(__dirname, '..', '..', '..');`,
  `Object.assign(exports, require(path.join(root, 'prisma', 'client.js')));`,
  ``,
].join('\n');

fs.writeFileSync(distIndex, shim, 'utf8');
console.log(`[link-runtime-client] linked runtime adapter -> ${distIndex}`);
